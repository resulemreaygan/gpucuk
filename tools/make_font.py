"""Renders a TrueType font into a 1-bit-per-pixel C header for the GPU'cuk firmware.

Only the characters the device needs are rendered: printable ASCII, the Turkish letters and a
few common punctuation marks and symbols. Characters the font does not have are skipped and reported.

The generated header is a derivative of the font, so it carries the font's license: ``--spdx``
(default ``OFL-1.1``, the SIL Open Font License of Noto Sans in tools/fonts).

Usage:
    make_font.py [--spdx OFL-1.1] <ttf> <pixel_size> <c_name> <out.h>

Author: Resul Emre Aygan
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

__author__ = "Resul Emre Aygan"

CHARSET = (
    [chr(c) for c in range(0x20, 0x7F)]
    + list("ÇĞİÖŞÜçğıöşü")
    + list("·…—–’“”°×")
)
THRESHOLD = 110  # 8-bit coverage at or above this becomes a black pixel


@dataclass
class Glyph:
    """One rendered character, laid out like ``struct Glyph`` in firmware/src/ui/Font.h."""

    codepoint: int
    width: int
    height: int
    x_offset: int
    y_offset: int
    advance: int
    rows: list[bytes] = field(default_factory=list)
    bitmap_offset: int = 0


def notdef_signature(font: ImageFont.FreeTypeFont) -> tuple[tuple[int, int], bytes]:
    """Returns the mask of the font's "missing glyph" box, to detect unsupported characters.

    Args:
        font: Loaded font.

    Returns:
        Mask size and pixels of U+FFFF, which no font defines.
    """
    mask = font.getmask("\uffff", mode="L")
    return mask.size, bytes(mask)


def render(font: ImageFont.FreeTypeFont, ch: str) -> Glyph:
    """Renders one character into byte-aligned rows, most significant bit first.

    Args:
        font: Loaded font.
        ch: Character to render.

    Returns:
        The glyph; empty characters such as space have no rows.
    """
    left, top, right, bottom = (int(v) for v in font.getbbox(ch, anchor="ls"))
    advance = round(font.getlength(ch))
    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return Glyph(ord(ch), 0, 0, 0, 0, advance)
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    coverage = img.tobytes()  # one byte per pixel, row by row
    rows: list[bytes] = []
    for y in range(h):
        row = bytearray((w + 7) // 8)
        for x in range(w):
            if coverage[y * w + x] >= THRESHOLD:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return Glyph(ord(ch), w, h, left, top, advance, rows)


def build_header(ttf: Path, size: int, name: str, spdx: str) -> tuple[str, int, int, str]:
    """Renders the character set and formats the C header.

    Args:
        ttf: TrueType font file.
        size: Pixel size.
        name: C identifier for the ``Font`` object; arrays get ``_bitmap`` and ``_glyphs`` suffixes.
        spdx: SPDX license identifier of the font.

    Returns:
        Header text, glyph count, bitmap size in bytes and the characters that were skipped.
    """
    font = ImageFont.truetype(str(ttf), size)
    notdef = notdef_signature(font)
    ascent, descent = font.getmetrics()

    glyphs: list[Glyph] = []
    bitmap = bytearray()
    skipped: list[str] = []
    for ch in sorted(set(CHARSET), key=ord):
        if ch != " ":
            m = font.getmask(ch, mode="L")
            if (m.size, bytes(m)) == notdef:
                skipped.append(ch)
                continue
        g = render(font, ch)
        g.bitmap_offset = len(bitmap)
        for r in g.rows:
            bitmap += r
        glyphs.append(g)

    family, style = font.getname()
    lines = [
        f"// SPDX-License-Identifier: {spdx}",
        "// Generated by tools/make_font.py — do not edit.",
        f"// Glyphs rendered from {ttf.name} ({family} {style}) @ {size}px; the font's license applies.",
        "#pragma once",
        '#include "../Font.h"',
        "",
        f"static const uint8_t {name}_bitmap[] = {{",
    ]
    for i in range(0, len(bitmap), 24):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in bitmap[i : i + 24]) + ",")
    lines += ["};", "", f"static const Glyph {name}_glyphs[] = {{"]
    for g in glyphs:
        lines.append(
            f"  {{0x{g.codepoint:04x}, {g.width}, {g.height}, {g.x_offset}, {g.y_offset}, {g.advance}, "
            f"{g.bitmap_offset}}},"
        )
    lines += [
        "};",
        "",
        f"static const Font {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bitmap, "
        f"{ascent + descent}, {ascent}}};",
        "",
    ]
    return "\n".join(lines), len(glyphs), len(bitmap), "".join(skipped)


def main() -> None:
    """Parses the command line and writes the header."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("ttf", type=Path, help="TrueType font file")
    ap.add_argument("size", type=int, help="pixel size")
    ap.add_argument("name", help="C identifier, e.g. font_body")
    ap.add_argument("out", type=Path, help="output header")
    ap.add_argument("--spdx", default="OFL-1.1", help="SPDX license identifier of the font")
    args = ap.parse_args()

    text, n_glyphs, n_bytes, skipped = build_header(args.ttf, args.size, args.name, args.spdx)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"{args.out}: {n_glyphs} glyphs, {n_bytes} bytes of bitmap, skipped: {skipped or '-'}")


if __name__ == "__main__":
    main()
